"""
Database module for IoT environmental sensor readings using Supabase PostgreSQL.

Communicates with Supabase's native PostgREST HTTPS API using standard library urllib,
ensuring zero extra heavy dependencies, fast Vercel serverless cold-starts,
and secure parameterized REST execution.
"""
import json
import logging
import urllib.error
import urllib.parse
import urllib.request
from datetime import datetime, timedelta, timezone

import config

logger = logging.getLogger("derma_sensor_db")

# Default HTTP timeout for Supabase API calls (seconds)
DEFAULT_TIMEOUT = 5.0


def is_configured() -> bool:
    """Return True if Supabase credentials are configured in the environment."""
    return bool(config.SUPABASE_URL and config.SUPABASE_SERVICE_ROLE_KEY)


def _get_headers() -> dict:
    """Construct authenticated headers for Supabase PostgREST requests."""
    return {
        "apikey": config.SUPABASE_SERVICE_ROLE_KEY,
        "Authorization": f"Bearer {config.SUPABASE_SERVICE_ROLE_KEY}",
        "Content-Type": "application/json",
        "Accept": "application/json",
    }


def insert_reading(
    device_id: str,
    temperature: float,
    humidity: float,
    recorded_at: str,
    timeout: float = DEFAULT_TIMEOUT,
) -> dict:
    """
    Insert a verified sensor reading into Supabase PostgreSQL.

    Parameters:
        device_id   : Unique hardware identifier (e.g., 'skin-monitor-pi')
        temperature : Measured ambient temperature in degrees Celsius
        humidity    : Measured relative humidity percentage (0-100)
        recorded_at : ISO 8601 UTC timestamp string generated by the server

    Returns:
        The inserted record dictionary.

    Raises:
        RuntimeError: If Supabase is unconfigured or returns an error.
    """
    if not is_configured():
        raise RuntimeError("Supabase credentials not configured (SUPABASE_URL, SUPABASE_SERVICE_ROLE_KEY).")

    endpoint = f"{config.SUPABASE_URL}/rest/v1/sensor_readings"
    payload = {
        "device_id": str(device_id),
        "temperature": round(float(temperature), 2),
        "humidity": round(float(humidity), 2),
        "recorded_at": str(recorded_at),
    }

    headers = _get_headers()
    headers["Prefer"] = "return=representation"

    data_bytes = json.dumps(payload).encode("utf-8")
    req = urllib.request.Request(endpoint, data=data_bytes, headers=headers, method="POST")

    try:
        with urllib.request.urlopen(req, timeout=timeout) as response:
            resp_body = response.read().decode("utf-8")
            records = json.loads(resp_body) if resp_body else []
            if isinstance(records, list) and len(records) > 0:
                return records[0]
            return payload
    except urllib.error.HTTPError as exc:
        err_msg = exc.read().decode("utf-8", errors="replace")
        logger.error(f"[Supabase HTTPError {exc.code}]: Failed to insert sensor reading.")
        raise RuntimeError(f"Database rejected insert (HTTP {exc.code}): {err_msg[:200]}") from None
    except urllib.error.URLError as exc:
        logger.error(f"[Supabase URLError]: Connection failed: {exc.reason}")
        raise RuntimeError(f"Failed to connect to Supabase: {exc.reason}") from None
    except Exception as exc:
        logger.error(f"[Supabase Exception]: Unexpected error during insert: {exc}")
        raise RuntimeError("Unexpected error while saving reading to database.") from None


def get_latest_reading(device_id: str = None, timeout: float = DEFAULT_TIMEOUT) -> dict | None:
    """
    Fetch the most recent sensor reading from Supabase PostgreSQL.

    Parameters:
        device_id : Optional filter by device ID. Defaults to config.EXPECTED_DEVICE_ID.

    Returns:
        dict of the latest record or None if no readings exist or credentials missing.
    """
    if not is_configured():
        return None

    target_device = device_id or config.EXPECTED_DEVICE_ID
    params = {
        "order": "recorded_at.desc",
        "limit": "1",
    }
    if target_device:
        params["device_id"] = f"eq.{target_device}"

    query_str = urllib.parse.urlencode(params)
    endpoint = f"{config.SUPABASE_URL}/rest/v1/sensor_readings?{query_str}"
    headers = _get_headers()

    req = urllib.request.Request(endpoint, headers=headers, method="GET")

    try:
        with urllib.request.urlopen(req, timeout=timeout) as response:
            resp_body = response.read().decode("utf-8")
            records = json.loads(resp_body) if resp_body else []
            if isinstance(records, list) and len(records) > 0:
                return records[0]
            return None
    except urllib.error.HTTPError as exc:
        logger.error(f"[Supabase HTTPError {exc.code}]: Failed to fetch latest reading.")
        return None
    except urllib.error.URLError as exc:
        logger.error(f"[Supabase URLError]: Connection failed: {exc.reason}")
        return None
    except Exception as exc:
        logger.error(f"[Supabase Exception]: Unexpected error fetching latest: {exc}")
        return None


def get_history(
    device_id: str = None,
    hours: int = 24,
    limit: int = 100,
    timeout: float = DEFAULT_TIMEOUT,
) -> list[dict]:
    """
    Fetch chronological sensor readings for the specified duration (up to limit records).

    Parameters:
        device_id : Optional filter by device ID.
        hours     : Number of past hours to query (default: 24).
        limit     : Maximum records to return (capped by config.SENSOR_HISTORY_LIMIT).

    Returns:
        List of reading dicts ordered chronologically.
    """
    if not is_configured():
        return []

    target_device = device_id or config.EXPECTED_DEVICE_ID
    effective_limit = min(int(limit), config.SENSOR_HISTORY_LIMIT)

    since_dt = datetime.now(timezone.utc) - timedelta(hours=max(1, hours))
    since_iso = since_dt.isoformat()

    params = {
        "recorded_at": f"gte.{since_iso}",
        "order": "recorded_at.asc",
        "limit": str(effective_limit),
    }
    if target_device:
        params["device_id"] = f"eq.{target_device}"

    query_str = urllib.parse.urlencode(params)
    endpoint = f"{config.SUPABASE_URL}/rest/v1/sensor_readings?{query_str}"
    headers = _get_headers()

    req = urllib.request.Request(endpoint, headers=headers, method="GET")

    try:
        with urllib.request.urlopen(req, timeout=timeout) as response:
            resp_body = response.read().decode("utf-8")
            records = json.loads(resp_body) if resp_body else []
            return records if isinstance(records, list) else []
    except Exception as exc:
        logger.error(f"[Supabase History Exception]: {exc}")
        return []
