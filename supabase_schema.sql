-- 1. Create sensor_readings table
CREATE TABLE IF NOT EXISTS public.sensor_readings (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    device_id TEXT NOT NULL,
    temperature NUMERIC(5, 2) NOT NULL,
    humidity NUMERIC(5, 2) NOT NULL,
    recorded_at TIMESTAMPTZ NOT NULL DEFAULT timezone('utc'::text, now())
);

-- 2. Add documentation comments
COMMENT ON TABLE public.sensor_readings IS 'Chronological IoT telemetry stream from Raspberry Pi 3 + DHT11 sensor.';
COMMENT ON COLUMN public.sensor_readings.device_id IS 'Hardware identifier of transmitting edge device (e.g., skin-monitor-pi).';
COMMENT ON COLUMN public.sensor_readings.temperature IS 'Ambient clinical room temperature in degrees Celsius (°C).';
COMMENT ON COLUMN public.sensor_readings.humidity IS 'Ambient relative humidity percentage (% RH).';
COMMENT ON COLUMN public.sensor_readings.recorded_at IS 'Server-validated UTC timestamp when the telemetry packet was received.';

-- 3. Composite index for ultra-fast latest-reading queries and history timeline queries
CREATE INDEX IF NOT EXISTS idx_sensor_readings_device_time 
ON public.sensor_readings (device_id, recorded_at DESC);

-- 4. Enable Row Level Security (RLS) to enforce strict zero-trust access control
ALTER TABLE public.sensor_readings ENABLE ROW LEVEL SECURITY;

-- 5. Revoke direct public / anonymous write privileges
REVOKE ALL ON TABLE public.sensor_readings FROM anon;
REVOKE ALL ON TABLE public.sensor_readings FROM authenticated;

-- 6. Grant full access exclusively to the server-side service_role
-- (Vercel Flask backend communicates using SUPABASE_SERVICE_ROLE_KEY)
GRANT ALL ON TABLE public.sensor_readings TO service_role;

-- 7. Define explicit RLS policy for service_role
CREATE POLICY "Service role unrestricted access to sensor_readings"
ON public.sensor_readings
FOR ALL
TO service_role
USING (true)
WITH CHECK (true);
